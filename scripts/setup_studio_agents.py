#!/usr/bin/env python3
"""Generate native project agent definitions from shared, readable role sources."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def definitions(root: Path = ROOT) -> dict[Path, str]:
    registry = json.loads((root / "config/studio-agents.json").read_text())
    files = {}
    for agent in registry["agents"]:
        body = (root / agent["source"]).read_text(encoding="utf-8")
        q = lambda s: json.dumps(s, ensure_ascii=False)
        toml = "# Generated by scripts/setup_studio_agents.py; edit agents/*.md instead.\n"
        toml += f'name = {q(agent["id"])}\ndescription = {q(agent["description"])}\ndeveloper_instructions = {q(body)}\n'
        if agent["id"] != "creative-director":
            toml += "\n[features]\napps = false\nplugins = false\n"
        files[root / ".codex/agents" / (agent["id"] + ".toml")] = toml
        front = f'---\nname: {agent["id"]}\ndescription: {q(agent["description"])}\nmodel: inherit\n'
        if agent["claude_tools"]:
            front += f'tools: {agent["claude_tools"]}\n'
        files[root / ".claude/agents" / (agent["id"] + ".md")] = front + "---\n\n" + body
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    errors = []
    for path, content in definitions().items():
        current = path.read_text() if path.exists() else None
        if args.check:
            if current != content:
                errors.append(str(path.relative_to(ROOT)))
        elif current is not None and current != content and not args.refresh:
            errors.append("Existing definition differs; inspect and use --refresh: " + str(path))
        elif current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    # Claude Code reads its native project skill directory; share canonical copies.
    if not args.check:
        target = ROOT / ".claude/skills"
        target.mkdir(parents=True, exist_ok=True)
        for skill in (ROOT / ".agents/skills").iterdir():
            if not (skill / "SKILL.md").is_file():
                continue
            link = target / skill.name
            if not link.exists() and not link.is_symlink():
                link.symlink_to(Path("../../.agents/skills") / skill.name, target_is_directory=True)
    print(json.dumps({"status": "needs_attention" if errors else "configured", "native_agent_files": 8, "errors": errors, "claude_runtime_tested": False}, ensure_ascii=False))
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
